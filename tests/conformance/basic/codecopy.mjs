import { chromium } from "playwright";
import { writeFileSync, mkdirSync } from "fs";
import { join } from "path";
import { randomUUID } from "crypto";
const TALKY = process.env.TALKY_HOME;
const base = "http://127.0.0.1:8785";
const id = randomUUID();
const dir = join(TALKY, "convos", id);
mkdirSync(dir, { recursive: true });
const at = Date.now() / 1000;
const code = 'def greet(name):\n    return f"hello, {name}"';
const list = [{ role: "user", content: "code please" }, { role: "assistant", content: "Sure:\n\n```python\n" + code + "\n```" }];
writeFileSync(join(dir, "transcript.jsonl"), list.map((t, i) => JSON.stringify({ ...t, timestamp: at - (list.length - i) * 5 })).join("\n") + "\n");
writeFileSync(join(dir, "convo.json"), JSON.stringify({ id, backend: "script", profile: "script", started_at: at - list.length * 5, last_active_at: at, title: "Seeded " + id.slice(0, 8), native_session_id: null, pinned: false, archived: false }));
await fetch(base + "/api/convos/new", { method: "POST" });
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 800 }, permissions: ["clipboard-read", "clipboard-write"] })).newPage();
p.on("console",(m)=>{if(m.text().includes("dbg"))console.log("[c]",m.text());});
p.on("pageerror", (e) => console.log("[pge]", String(e).slice(0, 300)));
await p.goto(base + "/", { waitUntil: "load" });
await p.waitForSelector(`[data-testid="session-row"][data-convo-id="${id}"]`, { timeout: 15000 });
await p.click(`[data-testid="session-row"][data-convo-id="${id}"]`);
await p.waitForSelector('[data-testid="code-copy"]', { timeout: 10000 });
await p.waitForTimeout(500);
const btn = p.locator('[data-testid="transcript-message"]').last().getByRole("button", { name: /^copy( code)?$/i }).first();
console.log("before:", await btn.evaluate((el) => (el.getAttribute("aria-label") || el.textContent)));
await p.evaluate(() => {
  globalThis.__obs = [];
  new MutationObserver((ms) => { for (const m of ms) globalThis.__obs.push(m.type + ":" + (m.target.textContent||"").slice(0,40)); }).observe(document.body, { childList: true, subtree: true, attributes: true });
});
await btn.click();
await p.waitForTimeout(600);
console.log("obs:", JSON.stringify(await p.evaluate(() => globalThis.__obs.slice(0, 30))));
for (const t of [50, 400, 1400]) {
  await p.waitForTimeout(t === 50 ? 50 : t - (t === 400 ? 50 : 400));
  console.log(`t=${t}:`, await btn.evaluate((el) => (el.getAttribute("aria-label") || el.textContent)));
}
console.log("clip:", await p.evaluate(() => navigator.clipboard.readText().catch(String)));
console.log("count:", await p.locator('[data-testid="code-copy"]').count());
await btn.click();
await p.waitForTimeout(100);
console.log("after2:", await btn.evaluate((el) => el.outerHTML.slice(0, 300)), "| count:", await p.locator('[data-testid="code-copy"]').count());
await p.waitForTimeout(300);
console.log("after2+300:", await btn.evaluate((el) => el.outerHTML.slice(0, 200)));
await b.close();
